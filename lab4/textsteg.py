"""Text steganography (sections 7.2 and 7.3).

Syntactic methods (the text stays the same, its formatting carries the bits):
  spaces     one space between words = 0, two spaces = 1
  invisible  ordinary space (code 32) = 1, no-break space (U+00A0, code 255 in
             DOS code page 866, 160 in Windows-1251) = 0
  case       letter case: lower = 0, upper = 1 (the manual's example
             "компьютер" + 01010 -> "кОмПьютер")
Lexical methods (the words change, the meaning does not):
  synonyms   a word from a synonym set of size N carries floor(log2 N) bits,
             or, with the mixed radix, the whole text carries floor(log2 prod N) bits
  mimicry    sentences generated by a context-free grammar, every two-way
             choice is one bit (the manual's "Иван поехал домой..." example)

Messages are coded in Windows-1251 (one byte per Russian or English letter, so
the container can be short) and end with a zero byte when the container has
room for it, so no length field is needed.
"""

import math
import random
import re
from typing import Dict, Iterator, List, NamedTuple, Optional, Sequence, Tuple

from lab4.bits import bits_to_int, bytes_to_bits, int_to_bits

CODEC = "cp1251"
NBSP = " "


def message_bits(message: str) -> List[int]:
    try:
        return bytes_to_bits(message.encode(CODEC))
    except UnicodeEncodeError:
        raise ValueError("Text methods code the message in Windows-1251: "
                         "only Russian and English letters, digits, punctuation") from None


def message_from_bits(bits: Sequence[int]) -> str:
    data = bytes(bits_to_int(bits[i:i + 8]) for i in range(0, len(bits) - 7, 8))
    return data.split(b"\x00", 1)[0].decode(CODEC, errors="replace")


def _fits(bits: Sequence[int], room: int, unit: str) -> None:
    if len(bits) > room:
        raise ValueError(f"The message needs {len(bits)} bits, the container holds "
                         f"{room} ({unit}): at most {room // 8} bytes")


# ---------------------------------------------------------------------- spaces
_GAP = re.compile(r"[  ]+")


def _gaps(text: str) -> List[re.Match]:
    return list(_GAP.finditer(text))


def spaces_capacity(container: str) -> int:
    """Bits: one per gap between words (n words give n - 1 bits)."""
    return len(_gaps(container))


def spaces_embed(container: str, bits: Sequence[int]) -> str:
    gaps = _gaps(container)
    _fits(bits, len(gaps), "gaps between words")
    out, last = [], 0
    for i, gap in enumerate(gaps):
        out.append(container[last:gap.start()])
        out.append("  " if i < len(bits) and bits[i] else " ")
        last = gap.end()
    out.append(container[last:])
    return "".join(out)


def spaces_extract(text: str) -> List[int]:
    return [1 if len(gap.group()) >= 2 else 0 for gap in _gaps(text)]


# ---------------------------------------------------------------------- invisible
def invisible_embed(container: str, bits: Sequence[int]) -> str:
    gaps = _gaps(container)
    _fits(bits, len(gaps), "gaps between words")
    out, last = [], 0
    for i, gap in enumerate(gaps):
        out.append(container[last:gap.start()])
        out.append(NBSP if i < len(bits) and not bits[i] else " ")
        last = gap.end()
    out.append(container[last:])
    return "".join(out)


def invisible_extract(text: str) -> List[int]:
    return [0 if NBSP in gap.group() else 1 for gap in _gaps(text)]


# ---------------------------------------------------------------------- case
def case_capacity(container: str) -> int:
    return sum(ch.isalpha() and ch.lower() != ch.upper() for ch in container)


def case_embed(container: str, bits: Sequence[int]) -> str:
    _fits(bits, case_capacity(container), "letters")
    out, i = [], 0
    for ch in container:
        if ch.isalpha() and ch.lower() != ch.upper():
            ch = ch.upper() if i < len(bits) and bits[i] else ch.lower()
            i += 1
        out.append(ch)
    return "".join(out)


def case_extract(text: str) -> List[int]:
    return [int(ch.isupper()) for ch in text if ch.isalpha() and ch.lower() != ch.upper()]


# ---------------------------------------------------------------------- synonyms
# Sets are sorted alphabetically: sender and receiver must order them the same way.
SYNONYMS: List[List[str]] = sorted(sorted(group) for group in [
    ["хороший", "отличный", "толковый", "умелый"],
    ["программист", "разработчик"],
    ["быстро", "оперативно", "скоро"],
    ["находит", "обнаруживает", "отыскивает"],
    ["ошибку", "неточность", "погрешность"],
    ["большом", "крупном", "огромном"],
    ["внимательно", "вдумчиво", "тщательно"],
    ["читает", "изучает", "просматривает"],
    ["сразу", "мгновенно", "немедленно", "тотчас"],
    ["видит", "замечает"],
    ["проблему", "неполадку"],
    ["такая", "подобная"],
    ["работа", "деятельность"],
    ["опыта", "практики"],
    ["терпения", "выдержки", "усидчивости"],
    ["важно", "существенно"],
    ["задача", "цель"],
])
WORD = re.compile(r"[A-Za-zА-Яа-яЁё]+")


class Slot(NamedTuple):
    start: int
    end: int
    group: List[str]
    index: int              # position of the current word in its set


def synonym_slots(text: str, groups: Sequence[Sequence[str]] = SYNONYMS) -> List[Slot]:
    lookup: Dict[str, Tuple[List[str], int]] = {}
    for group in groups:
        for i, word in enumerate(group):
            if word.lower() in lookup:
                raise ValueError(f"'{word}' belongs to two synonym sets: "
                                 "the receiver could not decode it")
            lookup[word.lower()] = (list(group), i)
    return [Slot(m.start(), m.end(), *lookup[m.group().lower()])
            for m in WORD.finditer(text) if m.group().lower() in lookup]


def synonyms_capacity(container: str, mixed: bool = False,
                      groups: Sequence[Sequence[str]] = SYNONYMS) -> int:
    sizes = [len(slot.group) for slot in synonym_slots(container, groups)]
    if mixed:
        return int(math.log2(math.prod(sizes))) if sizes else 0
    return sum(int(math.log2(n)) for n in sizes)


def _replace(container: str, slots: List[Slot], choices: List[int]) -> str:
    out, last = [], 0
    for slot, choice in zip(slots, choices):
        word = slot.group[choice]
        original = container[slot.start:slot.end]
        if original[0].isupper():
            word = word[0].upper() + word[1:]
        out += [container[last:slot.start], word]
        last = slot.end
    out.append(container[last:])
    return "".join(out)


def synonyms_embed(container: str, bits: Sequence[int], mixed: bool = False,
                   groups: Sequence[Sequence[str]] = SYNONYMS) -> str:
    slots = synonym_slots(container, groups)
    _fits(bits, synonyms_capacity(container, mixed, groups), "synonym choices")
    choices = []
    if mixed:
        # bits -> one number -> digits of the mixed-radix system (first word = lowest digit)
        room = synonyms_capacity(container, True, groups)
        value = bits_to_int(list(bits) + [0] * (room - len(bits)))
        for slot in slots:
            value, digit = divmod(value, len(slot.group))
            choices.append(digit)
    else:
        stream = iter(bits)
        for slot in slots:
            width = int(math.log2(len(slot.group)))
            chunk = [next(stream, 0) for _ in range(width)]
            choices.append(bits_to_int(chunk) if width else slot.index)
    return _replace(container, slots, choices)


def synonyms_extract(text: str, mixed: bool = False,
                     groups: Sequence[Sequence[str]] = SYNONYMS) -> List[int]:
    slots = synonym_slots(text, groups)
    if mixed:
        value = 0
        for slot in reversed(slots):
            value = value * len(slot.group) + slot.index
        room = synonyms_capacity(text, True, groups)
        return int_to_bits(value, room) if room else []
    bits: List[int] = []
    for slot in slots:
        width = int(math.log2(len(slot.group)))
        if width:
            if slot.index >= 1 << width:
                raise ValueError(f"'{slot.group[slot.index]}' cannot occur in a "
                                 "container built by this method")
            bits += int_to_bits(slot.index, width)
    return bits


# ---------------------------------------------------------------------- mimicry
# Context-free grammar from the manual (figure 7.3): every rule has two choices,
# the first one codes 0, the second one codes 1.
GRAMMAR: Dict[str, Tuple[str, str]] = {
    "существительное": ("Илья глагол", "Иван глагол"),
    "глагол": ("поехал куда", "пошел куда"),
    "куда": ("на работу, чтобы зачем", "домой, чтобы зачем"),
    "зачем": ("забрать что", "взять что"),
    "что": ("деньги.", "одежду."),
}
START = "существительное"


class Step(NamedTuple):
    sentence: str           # sentence before the choice, nonterminals still in it
    rule: str
    bit: int
    choice: str


def mimicry_sentence(bits: Sequence[int], trace: Optional[List[Step]] = None,
                     grammar: Dict[str, Tuple[str, str]] = GRAMMAR, start: str = START) -> str:
    """One sentence: expand the leftmost nonterminal, the next bit picks the rule."""
    sentence, stream = start, iter(bits)
    while True:
        words = sentence.split(" ")
        pos = next((i for i, w in enumerate(words) if w.rstrip(".,") in grammar), None)
        if pos is None:
            return sentence
        rule = words[pos].rstrip(".,")
        bit = next(stream, None)
        if bit is None:
            raise ValueError("Not enough bits for the grammar: give a filler")
        choice = grammar[rule][bit]
        if trace is not None:
            trace.append(Step(sentence, rule, bit, choice))
        words[pos] = choice
        sentence = " ".join(words)


def mimicry_depth(grammar: Dict[str, Tuple[str, str]] = GRAMMAR, start: str = START) -> int:
    """Bits per sentence (every path of this grammar has the same length)."""
    return sum(1 for _ in _walk_rules(grammar, start))


def _walk_rules(grammar: Dict[str, Tuple[str, str]], rule: str) -> Iterator[str]:
    while rule:
        yield rule
        rule = next((w.rstrip(".,") for w in grammar[rule][0].split()
                     if w.rstrip(".,") in grammar), "")


def mimicry_embed(bits: Sequence[int], seed: Optional[str] = None) -> str:
    """Sentences for a bit stream; the last one is completed with random filler bits."""
    depth = mimicry_depth()
    rng = random.Random(seed)
    padded = list(bits) + [rng.randrange(2) for _ in range(-len(bits) % depth)]
    return " ".join(mimicry_sentence(padded[i:i + depth]) for i in range(0, len(padded), depth))


def mimicry_extract(text: str, grammar: Dict[str, Tuple[str, str]] = GRAMMAR,
                    start: str = START) -> List[int]:
    """Parse the text back: at every node the choice that the text continues with."""
    bits: List[int] = []
    rest = text.strip()
    while rest:
        pending = [start]
        while pending:
            token = pending.pop(0)
            if token.rstrip(".,") in grammar:
                rule = token.rstrip(".,")
                for bit, choice in enumerate(grammar[rule]):
                    head = choice.split(" ")[0]
                    if rest.startswith(head):
                        bits.append(bit)
                        pending = choice.split(" ") + pending
                        break
                else:
                    raise ValueError(f"The text does not follow the grammar near: {rest[:30]!r}")
            else:
                if not rest.startswith(token):
                    raise ValueError(f"The text does not follow the grammar near: {rest[:30]!r}")
                rest = rest[len(token):].lstrip()
    return bits


METHODS = ("spaces", "invisible", "case", "synonyms", "mixed", "mimicry")


def embed(method: str, container: str, message: str, seed: Optional[str] = None) -> str:
    bits = message_bits(message)
    if len(bits) + 8 <= capacity(method, container):
        bits += [0] * 8          # terminator: the receiver stops at the zero byte
    if method == "spaces":
        return spaces_embed(container, bits)
    if method == "invisible":
        return invisible_embed(container, bits)
    if method == "case":
        return case_embed(container, bits)
    if method in ("synonyms", "mixed"):
        return synonyms_embed(container, bits, mixed=method == "mixed")
    if method == "mimicry":
        return mimicry_embed(bits, seed)
    raise ValueError(f"Unknown method {method}")


def extract_bits(method: str, text: str) -> List[int]:
    if method == "spaces":
        return spaces_extract(text)
    if method == "invisible":
        return invisible_extract(text)
    if method == "case":
        return case_extract(text)
    if method in ("synonyms", "mixed"):
        return synonyms_extract(text, mixed=method == "mixed")
    if method == "mimicry":
        return mimicry_extract(text)
    raise ValueError(f"Unknown method {method}")


def extract(method: str, text: str) -> str:
    return message_from_bits(extract_bits(method, text))


def capacity(method: str, container: str) -> int:
    """Bits the container can carry (mimicry: unlimited, it writes its own text)."""
    if method in ("spaces", "invisible"):
        return spaces_capacity(container)
    if method == "case":
        return case_capacity(container)
    if method in ("synonyms", "mixed"):
        return synonyms_capacity(container, mixed=method == "mixed")
    return math.inf  # type: ignore[return-value]
